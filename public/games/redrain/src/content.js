function buildContinuationVariant(base, index, laneIndex) {
  const lane = CONTINUATION_LANES[laneIndex];
  const copy = GENERIC_BRANCH_COPY[index]?.[laneIndex] || {};
  const labels = CONTINUATION_CHOICES[base.id]?.[laneIndex];
  if (!labels || labels.length !== base.choices.length) throw new Error(`Missing authored choices: ${base.id}/${laneIndex}`);
  const bridge = copy.bridge || copy.echo || lane.echo;
  return Object.freeze({
    ...base,
    id: `${base.id}--${lane.key}`,
    branch: copy.branch || lane.branch,
    branchType: "continuation",
    title: copy.title || `${base.title} / ${lane.titleCue}`,
    location: copy.location || base.location,
    body: humanizeBrief(copy.body || `${base.body}\n\n${bridge}`),
    quote: humanizeDialogue(copy.quote || `${copy.leadLine || lane.leadLine}\n${base.quote}`),
    signal: `${humanizeBrief(base.signal)}\n${humanizeBrief(copy.signal || lane.signal)}`,
    choices: base.choices.map((item, choiceIndex) => ({
      ...item,
      label: labels[choiceIndex],
      response: humanizeBrief(item.response + " " + (copy.resultTails?.[choiceIndex] || continuationResultTail(base, copy, lane, choiceIndex))),
      effects: mergeEffects(item.effects, lane.modifiers[choiceIndex]),
      tag: `${item.tag}-${lane.key}`
    })),
    routeChoice: laneIndex
  });
}

export const BRANCH_LAYERS = Object.freeze(Object.fromEntries(
  BRANCH_TARGET_INDICES.map((index) => {
    const base = SCENES[index];
    const rawVariants = RAW_BRANCH_LAYERS[index];
    const variants = rawVariants
      ? rawVariants.map((variant) => Object.freeze({
        ...base,
        ...variant,
        body: humanizeBrief(variant.body || base.body),
          quote: humanizeDialogue(variant.quote || base.quote),
        signal: humanizeBrief(variant.signal || base.signal),
        choices: (variant.choices || base.choices).map((item) => ({
          ...item,
          response: humanizeBrief(item.response)
        })),
        branchType: "pivotal",
        day: variant.day || base.day,
        time: variant.time || base.time,
        kicker: `${base.kicker} / ${variant.branch}`,
        rain: base.rain
      }))
      : CONTINUATION_LANES.map((_, laneIndex) => buildContinuationVariant(base, index, laneIndex));
    return [index, Object.freeze(variants)];
  })
));

