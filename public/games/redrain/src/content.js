export function getSceneForRoute(index, route = []) {
  const variants = BRANCH_LAYERS[index];
  if (variants) {
    const inboundChoice = route[index - 1];
    return decorateDangerScene(variants[Number.isInteger(inboundChoice) ? inboundChoice : 0] || variants[0], index, route);
  }

  return decorateDangerScene(SCENES[index] || null, index, route);
}

export function getBranchTrail(route = []) {
  return BRANCH_TARGET_INDICES
    .filter((targetIndex) => targetIndex - 1 < route.length)
    .map((targetIndex) => BRANCH_LAYERS[targetIndex][route[targetIndex - 1]]?.branch)
    .filter(Boolean);
}

export function getStorySequence(route = []) {
  return SCENES.map((_, index) => getSceneForRoute(index, route).id);
}

