export const PATH_COUNT = 3n ** BigInt(SCENES.length);

export function clampStat(value) {
  return Math.max(0, Math.min(600, value));
}

export function applyEffects(stats, effects) {
  const next = { ...stats };
  for (const { key } of STAT_DEFS) {
    next[key] = clampStat(next[key] + (effects[key] || 0));
  }
  return next;
}

export function getRouteCode(route) {
  return route.reduce((value, choiceIndex) => value * 3n + BigInt(choiceIndex), 0n);
}

export function getRouteSignature(route) {
  const code = getRouteCode(route).toString(36).toUpperCase().padStart(16, "0");
  const depth = route.length.toString(36).toUpperCase().padStart(2, "0");
  return "RB-" + depth + "-" + code;
}

export function getRouteRhythm(route) {
  const counts = [0, 0, 0];
  for (const choiceIndex of route) counts[choiceIndex] += 1;
  const spread = Math.max(...counts) - Math.min(...counts);
  if (spread <= 1) return 3;
  return counts.indexOf(Math.max(...counts));
}

export function getDominantStat(stats) {
  return STAT_DEFS.reduce(
    (best, item) => stats[item.key] > stats[best.key] ? item : best,
    STAT_DEFS[0]
  );
}

export function resolveEnding(stats, route) {
  const dominant = getDominantStat(stats);
  const statIndex = STAT_DEFS.findIndex((item) => item.key === dominant.key);
  const rhythm = getRouteRhythm(route);
  return ENDING_DEFS[statIndex * 4 + rhythm];
}
