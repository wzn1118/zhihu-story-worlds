const STAT_KEYS = Object.freeze(["trust", "supply", "memory", "signal", "courage"]);

function getChoiceEffects(focus, tag) {
  const focusIndex = STAT_KEYS.indexOf(focus);
  const hash = [...tag].reduce((value, character) => ((value * 33) + character.codePointAt(0)) >>> 0, 5381);
  const secondaryIndex = (focusIndex + 1 + (hash % 3)) % STAT_KEYS.length;
  let riskIndex = (focusIndex + 3 + (Math.floor(hash / 3) % 2)) % STAT_KEYS.length;
  if (riskIndex === secondaryIndex) riskIndex = (riskIndex + 1) % STAT_KEYS.length;
  return {
    [focus]: 8 + (hash % 5),
    [STAT_KEYS[secondaryIndex]]: 2 + (Math.floor(hash / 5) % 4),
    [STAT_KEYS[riskIndex]]: -(1 + (Math.floor(hash / 20) % 4))
  };
}

const branchChoice = (label, response, focus, tag) => ({
  label,
  response,
  effects: getChoiceEffects(focus, tag),
  tag
});

const branchScene = (branch, id, title, location, body, quote, signal, carry, choices, time, day) => ({
  branch,
  id,
  title,
  location,
  body,
  quote,
  signal,
  carry,
  choices: choices.map(([label, response, focus, tag]) => branchChoice(label, response, focus, tag)),
  ...(time ? { time } : {}),
  ...(day ? { day } : {})
});

