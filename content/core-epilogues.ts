export function closeCoreEpilogues(world: AuthoredWorld): AuthoredWorld {
  const nodes = structuredClone(world.nodes);
  for (const [id, text] of Object.entries(epilogues[world.id] ?? {})) {
    if (!nodes[id]?.ending) throw new Error(`Missing legacy epilogue: ${world.id}/${id}`);
    nodes[id].text = text;
    nodes[id].ending = { ...nodes[id].ending!, text: text.at(-1)! };
  }
  return { ...world, nodes };
}
