export function reviseLegacyB(world: AuthoredWorld): AuthoredWorld {
  const changeText = (choice: Choice, text: string) => {
    if (choice.text === text) return;
    choice.legacyTexts = [...new Set([...(choice.legacyTexts ?? []), choice.text])];
    choice.text = text;
  };
  for (const node of Object.values(world.nodes)) {
    const replacement = prose[world.id]?.[node.id];
    if (replacement) node.text = replacement.split('\n');
    node.chapter = node.ending ? '游戏原创结局 · 旧线' : '旧线改编';
    if (node.ending) node.ending.text = node.text.at(-1)!;
    const words = trialWords[world.id];
    if (words) {
      for (const choice of node.choices) {
        const match = /^(inspect|rush|answer|error|defer)_(\d)$/.exec(choice.id);
        if (match) {
          const col = ['inspect', 'rush', 'answer', 'error', 'defer'].indexOf(match[1]);
          changeText(choice, words[Number(match[2])][col]);
          // Keep outcome tone and substantive consequence, remove template
          // appendices telling the reader over and over to collect evidence.
          if (choice.feedback) choice.feedback.text = choice.feedback.text.split(' 已确认：')[0]
            .split(' 这次判断没有成立')[0].split(' 这一轮没有形成结论')[0];
          if (match[1] === 'inspect' || match[1] === 'rush') delete choice.feedback;
        }
        if (/^recover_/.test(choice.id)) changeText(choice, interludes[world.id][0]);
        if (/^advance_/.test(choice.id)) changeText(choice, interludes[world.id][1]);
        if (choice.id === 'prepare') changeText(choice, `${words[0][0]}，让自己定下神`);
        if (choice.id === 'coordinate') changeText(choice, words[0][1]);
      }
      if (node.id.startsWith('aftermath_')) {
        node.title = ['接下来的脚步', '话没说完，人已到门口', '这一趟留下什么', '临别的一步'][Number(node.id.slice(-1))];
        delete node.challenge;
      }
      // The dialogue itself now presents the dilemma; no duplicate generic
      // evidence lecture beneath it. Requirements and costs remain visible.
      if (node.id.startsWith('field_')) delete node.challenge;
    }
  }
  // These two old scenes can otherwise stall in externally depleted fixtures.
  // Additive exits leave every historic choice, requirement and effect intact.
  const exit = world.id === 'temple-heart' ? { from: 'visit', to: 'ending_boundary', text: '请邻人陪母女照料，自己回山养息' }
    : world.id === 'tiger-shelter' ? { from: 'border', to: 'ending_wander', text: '不再深入林边，沿缓坡离开这座山' } : null;
  if (exit) world.nodes[exit.from].choices.push({ id: 'b_old_depleted_exit', text: exit.text, nextNodeId: exit.to });
  return world;
}
