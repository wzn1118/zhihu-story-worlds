const revisions: Revision[] = [];
let id = '';
function target(path: string): any {
  let value: any = before.find(w => w.id === id)!;
  for (const key of path.split('.')) value = Array.isArray(value) && !/^\d+$/.test(key) ? value.find(x => x.id === key) : value[key];
  return value;
}
function edit(path: string, after: string, reason: string) {
  const old = target(path);
  if (typeof old !== 'string' || old === after) throw new Error(`Invalid edit ${id}/${path}`);
  if (revisions.some(r => r.worldId === id && r.path === path)) throw new Error(`Duplicate ${id}/${path}`);
  revisions.push({ worldId: id, path, before: old, after, reason, anchors: before.find(w => w.id === id)!.sourcePassages!.map(p => p.id) });
}
